// A verified upstream product artifact can be unpacked as part of the normal
// Gradle build. Without the property, the existing optional generated source
// directory is left untouched so source/JVM-only builds remain possible.
val androidSdkComponents = extensions
    .getByType<com.android.build.api.variant.ApplicationAndroidComponentsExtension>()
    .sdkComponents
val wawonaArtifactZipPath = providers.gradleProperty("wawonaArtifactZip")
    .orElse(providers.environmentVariable("WAWONA_ARTIFACT_ZIP"))
val wawonaArtifactZip = wawonaArtifactZipPath.map { rootProject.file(it) }

val prepareWawonaPayload = tasks.register<Exec>("prepareWawonaPayload") {
    val packager = rootProject.file("tools/package_wawona_apk.py")
    val generatedSource = layout.buildDirectory.dir("generated/wawona")

    inputs.file(packager)
    inputs.file(wawonaArtifactZip).optional()
    inputs.property("pinnedWawonaRevision", "d298ddd25726fec0977285aa5f57181110c966a6")
    inputs.property("androidNdkVersion", "30.0.16248370")
    outputs.dir(generatedSource)

    onlyIf("A reviewed Wawona product artifact ZIP was supplied") {
        wawonaArtifactZipPath.isPresent
    }

    doFirst {
        val artifact = wawonaArtifactZip.orNull
            ?: throw org.gradle.api.GradleException("wawonaArtifactZip was not resolved.")
        if (!artifact.isFile) {
            throw org.gradle.api.GradleException(
                "Wawona product artifact ZIP does not exist: ${artifact.absolutePath}"
            )
        }

        val osName = System.getProperty("os.name").lowercase()
        val osArch = System.getProperty("os.arch").lowercase()
        val ndkHostTag = when {
            osName.startsWith("linux") && osArch in setOf("x86_64", "amd64") -> "linux-x86_64"
            osName.startsWith("mac") && osArch in setOf("aarch64", "arm64") -> "darwin-arm64"
            osName.startsWith("mac") -> "darwin-x86_64"
            osName.startsWith("windows") -> "windows-x86_64"
            else -> throw org.gradle.api.GradleException(
                "Unsupported host for the pinned Wawona artifact packager: $osName/$osArch"
            )
        }
        val ndkDirectory = androidSdkComponents.ndkDirectory.get().asFile
        val readelfName = if (ndkHostTag.startsWith("windows")) {
            "llvm-readelf.exe"
        } else {
            "llvm-readelf"
        }
        val readelf = ndkDirectory.resolve(
            "toolchains/llvm/prebuilt/$ndkHostTag/bin/$readelfName"
        )
        if (!readelf.isFile) {
            throw org.gradle.api.GradleException(
                "NDK llvm-readelf is missing: ${readelf.absolutePath}"
            )
        }

        val pythonExecutable = if (osName.startsWith("windows")) "python" else "python3"
        commandLine(
            pythonExecutable,
            packager.absolutePath,
            "--artifact-zip",
            artifact.absolutePath,
            "--readelf",
            readelf.absolutePath,
            "--revision",
            "d298ddd25726fec0977285aa5f57181110c966a6",
            "--output",
            generatedSource.get().asFile.absolutePath
        )
    }
}

// The task runs before native-library and asset merge tasks snapshot these
// generated source directories.
tasks.named("preBuild") {
    dependsOn(prepareWawonaPayload)
}

